#!/usr/bin/env python3
"""The AETHORAX operations as QGroundControl mission commands, from the AETHORAX config.

    generate_mission_commands.py           write custom/res/AETHORAX-MavCmdInfoCommon.json
    generate_mission_commands.py --check   exit 1 if the file is not what the config gives
    [--config <dir>]                       the autonomy's config/ (default: the AETHORAX
                                           repository this one is a submodule of)

Each operation is a MAVLink user command (MAV_CMD_USER_n, or WAYPOINT_USER_n when it
has a position) with its own name, fields, units, defaults and limits. The file is
QGroundControl's own base list of commands (src/MissionManager/MavCmdInfoCommon.json)
plus the operations as full entries: only the base list may name a command, so the
operations cannot be overrides (AethoraxBaseFirmwarePlugin serves this file). The limits
are the ones the Jetson enforces, read from its config, so QGroundControl offers
exactly what the mission will accept: each value is written once
(software/jetson/autonomy/config/README.md). The Jetson's plan tool maps the same
command numbers to its operations (software/jetson/autonomy/src/plan/).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "res" / "AETHORAX-MavCmdInfoCommon.json"
UPSTREAM_BASE = HERE.parents[1] / "src" / "MissionManager" / "MavCmdInfoCommon.json"
DEFAULT_CONFIG = HERE.parents[2] / "software" / "jetson" / "autonomy" / "config"

MAV_CMD_USER_1 = 31010


def ros_parameter(file: Path, dotted: str):
    """A key of a ROS 2 parameter file, whichever node block holds it (the last one wins)."""
    found = None
    for block in (yaml.safe_load(file.read_text()) or {}).values():
        node = (block or {}).get("ros__parameters", {})
        for key in dotted.split("."):
            node = node.get(key) if isinstance(node, dict) else None
        if node is not None:
            found = node
    if found is None:
        raise SystemExit(f"{file}: `{dotted}` is required")
    return found


def dive(config: Path) -> dict:
    """Dive (behavior_trees/subtrees/dive.xml): straight down to a depth, at a descent speed."""
    model = config / "generated" / "performance_model.yaml"
    speeds = ros_parameter(model, "speeds.descent.speeds_mps")
    default_speed = ros_parameter(model, "profiles.descent.descent_speed")
    return {
        "id": MAV_CMD_USER_1,
        "rawName": "MAV_CMD_USER_1",
        "friendlyName": "Dive",
        "description": "AETHORAX Dive: straight down to the depth, at the descent speed, where the vehicle is. "
                       "The mission refuses a depth beyond its limit (config/missions/<mission>.yaml).",
        "category": "AETHORAX",
        "friendlyEdit": True,
        "param1": {"label": "Depth", "units": "m", "default": 5.0, "decimalPlaces": 1, "min": 0.0},
        "param2": {"label": "Speed", "units": "m/s", "default": round(float(default_speed), 2), "decimalPlaces": 2,
                   "min": round(float(speeds[0]), 2), "max": round(float(speeds[-1]), 2)},
    }


def build(config: Path) -> str:
    document = json.loads(UPSTREAM_BASE.read_text())
    operations = [dive(config)]
    upstream_ids = {entry["id"] for entry in document["mavCmdInfo"]}
    clash = [op["id"] for op in operations if op["id"] in upstream_ids]
    if clash:
        raise SystemExit(f"QGroundControl's base list already has commands {clash}")
    document["comment"] = ("GENERATED by custom/tools/generate_mission_commands.py: QGroundControl's "
                           "src/MissionManager/MavCmdInfoCommon.json plus the AETHORAX operations, "
                           "from the AETHORAX config. Do not edit.")
    document["mavCmdInfo"] = document["mavCmdInfo"] + operations
    return json.dumps(document, indent=4) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    args = parser.parse_args()
    text = build(args.config)
    if args.check:
        if not OUT.is_file() or OUT.read_text() != text:
            print(f"{OUT} is stale: run custom/tools/generate_mission_commands.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
